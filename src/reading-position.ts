export type ReadingBox={top:number;height:number;width:number};
export type ReadingAnchor={index:number;y:number;x:number};

export function captureReadingAnchor(boxes:ReadingBox[],top:number,left=0,inset=0):ReadingAnchor|undefined{
  if(!boxes.length)return;
  const point=top+inset;
  let low=0,high=boxes.length-1;
  while(low<high){const middle=Math.ceil((low+high)/2);if(boxes[middle].top<=point)low=middle;else high=middle-1;}
  const box=boxes[low];
  return {index:low,y:(point-box.top)/Math.max(1,box.height),x:left/Math.max(1,box.width)};
}

export function restoreReadingAnchor(boxes:ReadingBox[],anchor:ReadingAnchor,inset=0){
  const box=boxes[anchor.index];
  return box?{top:Math.max(0,box.top+box.height*anchor.y-inset),left:Math.max(0,box.width*anchor.x)}:undefined;
}

// Capture before a layout change and restore against the new geometry. A scroll
// generated by resizing must not overwrite the last known reading position.
export function preserveReadingPosition(port:HTMLElement,selector:string,inset:()=>number=()=>0,onRestore?:()=>void){
  const items=Array.from(port.querySelectorAll<HTMLElement>(selector));
  if(!items.length)return {capture:()=>{},disconnect:()=>{}};
  const first=items[0],last=items[items.length-1];
  const oldAnchoring=port.style.overflowAnchor;port.style.overflowAnchor='none';
  const rect=(item:HTMLElement):ReadingBox=>{const bounds=item.getBoundingClientRect();return {top:bounds.top-port.getBoundingClientRect().top+port.scrollTop,height:bounds.height,width:bounds.width};};
  const signature=()=>{const a=rect(first),b=rect(last);return [port.clientWidth,port.clientHeight,a.top,a.height,a.width,b.top,b.height,b.width,inset()];};
  let boxes:ReadingBox[]=[],stamp:number[]=[],anchor:ReadingAnchor|undefined;
  let restoring=false;
  function capture(){boxes=items.map(rect);stamp=signature();anchor=captureReadingAnchor(boxes,port.scrollTop,port.scrollLeft,inset());}
  function changed(next:number[]){return next.some((value,index)=>Math.abs(value-stamp[index])>.5);}
  function maintain(){
    if(restoring)return;
    if(!changed(signature()))return;
    const retained=anchor;restoring=true;
    boxes=items.map(rect);stamp=signature();
    const point=retained&&restoreReadingAnchor(boxes,retained,inset());
    if(point){port.scrollTop=point.top;port.scrollLeft=point.left;}
    anchor=captureReadingAnchor(boxes,port.scrollTop,port.scrollLeft,inset());
    restoring=false;onRestore?.();
  }
  function scroll(){if(changed(signature()))maintain();else anchor=captureReadingAnchor(boxes,port.scrollTop,port.scrollLeft,inset());}
  capture();
  const observer=new ResizeObserver(maintain);
  for(const item of new Set([port,first,last,first.parentElement].filter((item):item is HTMLElement=>!!item)))observer.observe(item);
  port.addEventListener('scroll',scroll,{passive:true});
  port.addEventListener('reader:position-changed',capture);
  return {capture,disconnect(){observer.disconnect();port.removeEventListener('scroll',scroll);port.removeEventListener('reader:position-changed',capture);port.style.overflowAnchor=oldAnchoring;}};
}
